-- 1. USERS
-- Stores registered users
CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    LOCATION VARCHAR2(100),
    BIO VARCHAR2(500),
    PROFILE_PICTURE VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
);


-- 2. CATEGORIES
-- Stores categories used to organize skills
CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CATEGORY_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),

    CONSTRAINT PK_CATEGORIES PRIMARY KEY (CATEGORY_ID),
    CONSTRAINT UQ_CATEGORIES_NAME UNIQUE (CATEGORY_NAME)
);


-- 3. SKILLS
-- Stores individual skills under categories
CREATE TABLE SKILLS (
    SKILL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CATEGORY_ID NUMBER NOT NULL,
    SKILL_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),

    CONSTRAINT PK_SKILLS PRIMARY KEY (SKILL_ID),
    CONSTRAINT UQ_SKILLS_NAME UNIQUE (SKILL_NAME),

    CONSTRAINT FK_SKILLS_CATEGORY
        FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORIES(CATEGORY_ID)
);


-- 4. SKILLOFFERINGS
-- Skills that users can teach
CREATE TABLE SKILLOFFERINGS (
    OFFERING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    SKILL_ID NUMBER NOT NULL,
    PROFICIENCY_LEVEL VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_SKILLOFFERINGS PRIMARY KEY (OFFERING_ID),

    CONSTRAINT FK_OFFERINGS_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT FK_OFFERINGS_SKILL
        FOREIGN KEY (SKILL_ID)
        REFERENCES SKILLS(SKILL_ID),

    CONSTRAINT UQ_OFFERING_USER_SKILL
        UNIQUE (USER_ID, SKILL_ID),

    CONSTRAINT CK_OFFERING_PROFICIENCY
        CHECK (
            PROFICIENCY_LEVEL IN
            ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT')
        )
);


-- 5. SKILLREQUESTS
-- Skills that users want to learn
CREATE TABLE SKILLREQUESTS (
    REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    SKILL_ID NUMBER NOT NULL,
    EXPECTED_TEACHER_PROFICIENCY VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_SKILLREQUESTS PRIMARY KEY (REQUEST_ID),

    CONSTRAINT FK_REQUESTS_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT FK_REQUESTS_SKILL
        FOREIGN KEY (SKILL_ID)
        REFERENCES SKILLS(SKILL_ID),

    CONSTRAINT UQ_REQUEST_USER_SKILL
        UNIQUE (USER_ID, SKILL_ID),

    CONSTRAINT CK_REQUEST_PROFICIENCY
        CHECK (
            EXPECTED_TEACHER_PROFICIENCY IN
            ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT')
        )
);


-- 6. USERPREFERENCES
-- Stores one preference record per user
CREATE TABLE USERPREFERENCES (
    PREFERENCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    PREFERRED_MODE VARCHAR2(10) DEFAULT 'EITHER' NOT NULL,
    PREFERRED_LOCATION VARCHAR2(100),
    MINIMUM_TEACHER_RATING NUMBER(2,1) DEFAULT 0 NOT NULL,
    PREFERRED_SESSION_DURATION NUMBER DEFAULT 60 NOT NULL,
    PREFERRED_SESSION_FREQUENCY NUMBER,

    CONSTRAINT PK_USERPREFERENCES PRIMARY KEY (PREFERENCE_ID),

    CONSTRAINT FK_PREFERENCES_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT UQ_PREFERENCES_USER UNIQUE (USER_ID),

    CONSTRAINT CK_PREFERRED_MODE
        CHECK (PREFERRED_MODE IN ('ONLINE', 'OFFLINE', 'EITHER')),

    CONSTRAINT CK_MINIMUM_RATING
        CHECK (MINIMUM_TEACHER_RATING BETWEEN 0 AND 5),

    CONSTRAINT CK_PREFERENCE_DURATION
        CHECK (PREFERRED_SESSION_DURATION > 0),

    CONSTRAINT CK_PREFERENCE_FREQUENCY
        CHECK (
            PREFERRED_SESSION_FREQUENCY IS NULL
            OR PREFERRED_SESSION_FREQUENCY > 0
        )
);


-- 7. AVAILABILITY
-- Stores users' available days and time periods
CREATE TABLE AVAILABILITY (
    AVAILABILITY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    DAY_OF_WEEK VARCHAR2(10) NOT NULL,
    START_TIME VARCHAR2(5) NOT NULL,
    END_TIME VARCHAR2(5) NOT NULL,

    CONSTRAINT PK_AVAILABILITY PRIMARY KEY (AVAILABILITY_ID),

    CONSTRAINT FK_AVAILABILITY_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT CK_AVAILABILITY_DAY
        CHECK (
            DAY_OF_WEEK IN (
                'MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY',
                'FRIDAY', 'SATURDAY', 'SUNDAY'
            )
        ),

    CONSTRAINT CK_AVAILABILITY_START
        CHECK (
            REGEXP_LIKE(
                START_TIME,
                '^([01][0-9]|2[0-3]):[0-5][0-9]$'
            )
        ),

    CONSTRAINT CK_AVAILABILITY_END
        CHECK (
            REGEXP_LIKE(
                END_TIME,
                '^([01][0-9]|2[0-3]):[0-5][0-9]$'
            )
        ),

    CONSTRAINT CK_AVAILABILITY_PERIOD
        CHECK (START_TIME < END_TIME)
);


-- 8. MATCHES
-- Represents a match between two different users
CREATE TABLE MATCHES (
    MATCH_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_A_ID NUMBER NOT NULL,
    USER_B_ID NUMBER NOT NULL,
    SKILL_A_TEACHES NUMBER NOT NULL,
    SKILL_B_TEACHES NUMBER NOT NULL,
    STATUS VARCHAR2(10) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_MATCHES PRIMARY KEY (MATCH_ID),

    CONSTRAINT FK_MATCH_USER_A
        FOREIGN KEY (USER_A_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT FK_MATCH_USER_B
        FOREIGN KEY (USER_B_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT FK_MATCH_SKILL_A
        FOREIGN KEY (SKILL_A_TEACHES)
        REFERENCES SKILLS(SKILL_ID),

    CONSTRAINT FK_MATCH_SKILL_B
        FOREIGN KEY (SKILL_B_TEACHES)
        REFERENCES SKILLS(SKILL_ID),

    CONSTRAINT CK_MATCH_DIFFERENT_USERS
        CHECK (USER_A_ID <> USER_B_ID),

    CONSTRAINT CK_MATCH_STATUS
        CHECK (
            STATUS IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')
        )
);


-- 9. SESSIONS
-- Scheduled learning sessions belonging to a match
CREATE TABLE SESSIONS (
    SESSION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MATCH_ID NUMBER NOT NULL,
    SCHEDULED_DATE DATE NOT NULL,
    START_TIME VARCHAR2(5) NOT NULL,
    DURATION_MINUTES NUMBER NOT NULL,
    SESSION_MODE VARCHAR2(10) NOT NULL,
    LOCATION VARCHAR2(200),
    STATUS VARCHAR2(12) DEFAULT 'SCHEDULED' NOT NULL,

    CONSTRAINT PK_SESSIONS PRIMARY KEY (SESSION_ID),

    CONSTRAINT FK_SESSIONS_MATCH
        FOREIGN KEY (MATCH_ID)
        REFERENCES MATCHES(MATCH_ID),

    CONSTRAINT CK_SESSION_DURATION
        CHECK (DURATION_MINUTES > 0),

    CONSTRAINT CK_SESSION_MODE
        CHECK (SESSION_MODE IN ('ONLINE', 'OFFLINE')),

    CONSTRAINT CK_SESSION_STATUS
        CHECK (STATUS IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),

    CONSTRAINT CK_SESSION_START
        CHECK (
            REGEXP_LIKE(
                START_TIME,
                '^([01][0-9]|2[0-3]):[0-5][0-9]$'
            )
        )
);


-- 10. REVIEWS
-- Users review one another after sessions
CREATE TABLE REVIEWS (
    REVIEW_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SESSION_ID NUMBER NOT NULL,
    REVIEWER_ID NUMBER NOT NULL,
    REVIEWEE_ID NUMBER NOT NULL,
    RATING NUMBER(1) NOT NULL,
    FEEDBACK VARCHAR2(1000),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_REVIEWS PRIMARY KEY (REVIEW_ID),

    CONSTRAINT FK_REVIEWS_SESSION
        FOREIGN KEY (SESSION_ID)
        REFERENCES SESSIONS(SESSION_ID),

    CONSTRAINT FK_REVIEWS_REVIEWER
        FOREIGN KEY (REVIEWER_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT FK_REVIEWS_REVIEWEE
        FOREIGN KEY (REVIEWEE_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT UQ_SESSION_REVIEWER
        UNIQUE (SESSION_ID, REVIEWER_ID),

    CONSTRAINT CK_REVIEW_DIFFERENT_USERS
        CHECK (REVIEWER_ID <> REVIEWEE_ID),

    CONSTRAINT CK_REVIEW_RATING
        CHECK (RATING BETWEEN 1 AND 5)
);


