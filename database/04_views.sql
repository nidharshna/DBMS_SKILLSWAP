
-- 04_views.sql
-- SkillSwap: Reusable database views

-- VIEW 1: Users and the skills they can teach
CREATE OR REPLACE VIEW V_USER_SKILLS AS
SELECT
    U.USER_ID,
    U.NAME AS USER_NAME,
    S.SKILL_NAME,
    SO.PROFICIENCY_LEVEL
FROM USERS U
JOIN SKILLOFFERINGS SO
    ON U.USER_ID = SO.USER_ID
JOIN SKILLS S
    ON SO.SKILL_ID = S.SKILL_ID;


-- VIEW 2: Users and the skills they want to learn
CREATE OR REPLACE VIEW V_SKILL_REQUESTS AS
SELECT
    U.USER_ID,
    U.NAME AS USER_NAME,
    S.SKILL_NAME,
    SR.EXPECTED_TEACHER_PROFICIENCY
FROM USERS U
JOIN SKILLREQUESTS SR
    ON U.USER_ID = SR.USER_ID
JOIN SKILLS S
    ON SR.SKILL_ID = S.SKILL_ID;


-- VIEW 3: Match details and exchanged skills
CREATE OR REPLACE VIEW V_MATCH_DETAILS AS
SELECT
    M.MATCH_ID,
    UA.NAME AS USER_A,
    UB.NAME AS USER_B,
    SA.SKILL_NAME AS USER_A_TEACHES,
    SB.SKILL_NAME AS USER_B_TEACHES,
    M.STATUS,
    M.CREATED_AT
FROM MATCHES M
JOIN USERS UA
    ON M.USER_A_ID = UA.USER_ID
JOIN USERS UB
    ON M.USER_B_ID = UB.USER_ID
JOIN SKILLS SA
    ON M.SKILL_A_TEACHES = SA.SKILL_ID
JOIN SKILLS SB
    ON M.SKILL_B_TEACHES = SB.SKILL_ID;