-- SkillSwap: Basic data retrieval and reporting queries

-- QUERY 1: Display all registered users
SELECT *
FROM USERS
ORDER BY USER_ID;


-- QUERY 2: Display all skills with their categories
SELECT
    S.SKILL_ID,
    S.SKILL_NAME,
    C.CATEGORY_NAME,
    S.DESCRIPTION
FROM SKILLS S
JOIN CATEGORIES C
    ON S.CATEGORY_ID = C.CATEGORY_ID
ORDER BY C.CATEGORY_NAME, S.SKILL_NAME;


-- QUERY 3: Find the skills each user can teach
SELECT
    U.NAME AS USER_NAME,
    S.SKILL_NAME,
    SO.PROFICIENCY_LEVEL
FROM SKILLOFFERINGS SO
JOIN USERS U
    ON SO.USER_ID = U.USER_ID
JOIN SKILLS S
    ON SO.SKILL_ID = S.SKILL_ID
ORDER BY U.NAME;


-- QUERY 4: Find the skills each user wants to learn
SELECT
    U.NAME AS USER_NAME,
    S.SKILL_NAME,
    SR.EXPECTED_TEACHER_PROFICIENCY
FROM SKILLREQUESTS SR
JOIN USERS U
    ON SR.USER_ID = U.USER_ID
JOIN SKILLS S
    ON SR.SKILL_ID = S.SKILL_ID
ORDER BY U.NAME;


-- QUERY 5: Display user preferences
SELECT
    U.NAME,
    UP.PREFERRED_MODE,
    UP.PREFERRED_LOCATION,
    UP.MINIMUM_TEACHER_RATING,
    UP.PREFERRED_SESSION_DURATION,
    UP.PREFERRED_SESSION_FREQUENCY
FROM USERPREFERENCES UP
JOIN USERS U
    ON UP.USER_ID = U.USER_ID
ORDER BY U.NAME;


-- QUERY 6: Display available days and times for each user
SELECT
    U.NAME,
    A.DAY_OF_WEEK,
    A.START_TIME,
    A.END_TIME
FROM AVAILABILITY A
JOIN USERS U
    ON A.USER_ID = U.USER_ID
ORDER BY U.NAME;


-- QUERY 7: Display matches and their current status
SELECT
    M.MATCH_ID,
    UA.NAME AS USER_A,
    UB.NAME AS USER_B,
    SA.SKILL_NAME AS USER_A_TEACHES,
    SB.SKILL_NAME AS USER_B_TEACHES,
    M.STATUS
FROM MATCHES M
JOIN USERS UA
    ON M.USER_A_ID = UA.USER_ID
JOIN USERS UB
    ON M.USER_B_ID = UB.USER_ID
JOIN SKILLS SA
    ON M.SKILL_A_TEACHES = SA.SKILL_ID
JOIN SKILLS SB
    ON M.SKILL_B_TEACHES = SB.SKILL_ID
ORDER BY M.MATCH_ID;


-- QUERY 8: Display sessions with both participants
SELECT
    SE.SESSION_ID,
    UA.NAME AS USER_A,
    UB.NAME AS USER_B,
    SE.SCHEDULED_DATE,
    SE.START_TIME,
    SE.DURATION_MINUTES,
    SE.SESSION_MODE,
    SE.STATUS
FROM SESSIONS SE
JOIN MATCHES M
    ON SE.MATCH_ID = M.MATCH_ID
JOIN USERS UA
    ON M.USER_A_ID = UA.USER_ID
JOIN USERS UB
    ON M.USER_B_ID = UB.USER_ID
ORDER BY SE.SCHEDULED_DATE;


-- QUERY 9: Display reviews with reviewer and reviewee names
SELECT
    R.REVIEW_ID,
    SE.SESSION_ID,
    REVIEWER.NAME AS REVIEWER_NAME,
    REVIEWEE.NAME AS REVIEWEE_NAME,
    R.RATING,
    R.FEEDBACK
FROM REVIEWS R
JOIN USERS REVIEWER
    ON R.REVIEWER_ID = REVIEWER.USER_ID
JOIN USERS REVIEWEE
    ON R.REVIEWEE_ID = REVIEWEE.USER_ID
JOIN SESSIONS SE
    ON R.SESSION_ID = SE.SESSION_ID
ORDER BY R.REVIEW_ID;


-- QUERY 10: Calculate the average rating received by each user
SELECT
    U.NAME,
    ROUND(AVG(R.RATING), 2) AS AVERAGE_RATING,
    COUNT(R.REVIEW_ID) AS TOTAL_REVIEWS
FROM USERS U
LEFT JOIN REVIEWS R
    ON U.USER_ID = R.REVIEWEE_ID
GROUP BY U.USER_ID, U.NAME
ORDER BY U.NAME;